// Build the static web demo (docs/) from the single source of truth:
//   src/core.mjs      -> docs/core.mjs   (byte-identical copy)
//   fixtures/*.mjs    -> docs/fixtures.js (embedded, same objects)
// The demo therefore runs the EXACT same analysis as the CLI and the tests.
import { copyFile, readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const root = new URL('..', import.meta.url).pathname;

await mkdir(`${root}docs`, { recursive: true });

// 1. Core — byte-identical copy.
await copyFile(`${root}src/core.mjs`, `${root}docs/core.mjs`);

// 2. Fixtures — import each module, then emit one JS file with the data.
const files = (await readdir(`${root}fixtures`)).filter((f) => f.endsWith('.mjs')).sort();
const fixtures = {};
for (const file of files) {
  const mod = await import(pathToFileURL(`${root}fixtures/${file}`).href);
  const p = mod.default;
  fixtures[p.id] = p;
}
await writeFile(
  `${root}docs/fixtures.js`,
  `// Generated by scripts/build-demo.mjs — do not edit by hand.\n` +
    `export const FIXTURES = ${JSON.stringify(fixtures, null, 2)};\n`,
);

console.log(`demo built: core.mjs copied, ${files.length} fixtures embedded`);
